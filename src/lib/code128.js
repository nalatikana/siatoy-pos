/* แปลงข้อความเป็นลำดับโมดูล  คืน {modules, runs}
 * runs = ความกว้างของแท่งเรียงกัน (ดำ ขาว ดำ ขาว …) หน่วยเป็นโมดูล
 * ตัวเลขล้วนจำนวนคู่จะเข้ารหัสแบบ Start C ทำให้บาร์โค้ดสั้นลงราว 25%
 */
export function encode128(data) {
  data = String(data || '');
  const codes = [];
  const numericPair = /^\d+$/.test(data) && data.length % 2 === 0 && data.length >= 4;
  if (numericPair) {
    codes.push(105);
    for (let i = 0; i < data.length; i += 2) codes.push(parseInt(data.substr(i, 2), 10));
  } else {
    codes.push(104);
    for (const ch of data) { let v = ch.charCodeAt(0) - 32; if (v < 0 || v > 94) v = 0; codes.push(v); }
  }
  let sum = codes[0];
  for (let i = 1; i < codes.length; i++) sum += codes[i] * i;
  codes.push(sum % 103);
  codes.push(106);

  const runs = [];
  let modules = 0;
  for (const c of codes) {
    for (const ch of C128[c]) { const w = +ch; runs.push(w); modules += w; }
  }
  return { runs, modules, mode: numericPair ? 'C' : 'B' };
}

/* เติม 0 ข้างหน้าให้เลขเป็นจำนวนคู่ เพื่อให้เข้ารหัสแบบ Start C ได้
 * เครื่องยิงอ่านได้ทั้งสองแบบ ค่าที่อ่านออกมาจะมี 0 นำหน้าติดมาด้วย
 * ระบบค้นหาสินค้าตัด 0 นำหน้าทิ้งอยู่แล้ว จึงยิงได้ทั้งคู่ */
export const padEven = code => {
  code = String(code || '').trim();
  return (/^\d+$/.test(code) && code.length % 2 === 1) ? '0' + code : code;
};

/* วาดเป็น SVG โดยยึดความกว้างโมดูลตามที่สั่งมาเป็นมิลลิเมตร
 * ไม่ยืดให้เต็มความกว้างดวง เพราะแท่งจะไปตกที่เศษของจุดเครื่องพิมพ์
 * แล้วเครื่องปัดเอาเอง ทำให้แท่งกว้างไม่เท่ากันและยิงไม่ติดเป็นบางดวง */
export function svg128(data, moduleMm, heightMm) {
  const { runs, modules } = encode128(data);
  let x = 0, rects = '';
  runs.forEach((w, i) => {
    if (i % 2 === 0) rects += `<rect x="${x}" y="0" width="${w}" height="10" />`;
    x += w;
  });
  const wMm = (modules * moduleMm).toFixed(3);
  return `<svg class="bc" width="${wMm}mm" height="${heightMm}mm" viewBox="0 0 ${modules} 10"
    preserveAspectRatio="none" shape-rendering="crispEdges" fill="#000"
    xmlns="http://www.w3.org/2000/svg" style="display:block;margin:0 auto">${rects}</svg>`;
}
