let current = 'start';

function draw() {
  const sec = SECTIONS.find(s => s.id === current) || SECTIONS[0];
  const box = document.getElementById('modalBox');
  box.querySelector('#hpBody').innerHTML = `<h3 style="margin:0 0 12px;font-weight:600;font-size:18px">
      ${sec.icon} ${sec.title}</h3>${sec.html}`;
  box.querySelectorAll('[data-sec]').forEach(b =>
    b.classList.toggle('on', b.dataset.sec === current));
  box.querySelector('#hpBody').scrollTop = 0;
}

export function openHelp(section) {
  current = section && SECTIONS.some(s => s.id === section) ? section : 'start';
  openModal(`
    <div class="modal-head"><h3>📖 คู่มือการใช้งาน</h3><button class="x" id="hpClose">✕</button></div>
    <div class="modal-body" style="padding:0">
      <div class="help-wrap">
        <div class="help-nav">
          ${SECTIONS.map(s => `<button data-sec="${s.id}" class="${s.id === current ? 'on' : ''}">
            <span>${s.icon}</span> ${s.title}</button>`).join('')}
        </div>
        <div class="help-body" id="hpBody"></div>
      </div>
    </div>
    <div class="modal-foot"><span class="mini">เปิดคู่มือนี้ได้ตลอดจากปุ่ม ? มุมขวาบน</span>
      <button class="btn gold right" id="hpOk">เข้าใจแล้ว</button></div>`, true);
  const box = document.getElementById('modalBox');
  box.querySelector('#hpClose').onclick = box.querySelector('#hpOk').onclick = closeModal;
  box.querySelector('.help-nav').onclick = e => {
    const b = e.target.closest('[data-sec]'); if (!b) return;
    current = b.dataset.sec; draw();
  };
  draw();
}

/* เด้งคู่มือให้ดูครั้งแรกที่เปิดแอปบนเครื่องนั้น */
export async function maybeShowFirstTime() {
  if (await metaGet('helpSeen')) return;
  await metaSet('helpSeen', true);
  setTimeout(() => openHelp('start'), 900);
}
